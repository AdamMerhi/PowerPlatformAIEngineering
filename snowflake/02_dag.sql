-- Task DAG: ingest -> clean -> publish. Run as POC_ROLE.
-- Scoring is gone: assessments come from the Agent API (Advisor) and are written to CURATED.CLAIM_ASSESSMENTS.
USE ROLE POC_ROLE;
USE WAREHOUSE CLAIMS_WH;
USE DATABASE CLAIMS_POC;

-- Root: simulate new motor claims arriving every 5 minutes
CREATE OR REPLACE TASK CURATED.T_INGEST
  WAREHOUSE = CLAIMS_WH
  SCHEDULE = '5 MINUTE'
AS
  INSERT INTO RAW.CLAIMS_RAW (CLAIM_ID, POLICY_NUMBER, LOSS_DATE, LOSS_TYPE, NARRATIVE, CLAIMED_AMOUNT, REPORTED_AT)
  SELECT 'CLM' || REPLACE(UUID_STRING(), '-', ''),
         'POL' || LPAD(UNIFORM(0, 499, RANDOM())::STRING, 6, '0'),
         DATEADD(day, -UNIFORM(0, 5, RANDOM()), CURRENT_DATE()),
         'Collision',
         'Synthetic streaming motor claim. Insured vehicle was damaged in a low-speed collision in a car park.',
         UNIFORM(300, 60000, RANDOM()),
         CURRENT_TIMESTAMP()
  FROM TABLE(GENERATOR(ROWCOUNT => 3));

CREATE OR REPLACE TASK CURATED.T_CLEAN
  WAREHOUSE = CLAIMS_WH
  AFTER CURATED.T_INGEST
AS
  BEGIN
    MERGE INTO CLEAN.POLICIES t USING (
      SELECT POLICY_NUMBER, PRODUCT, START_DATE, SUM_INSURED FROM RAW.POLICIES_RAW
      QUALIFY ROW_NUMBER() OVER (PARTITION BY POLICY_NUMBER ORDER BY INGESTED_AT DESC) = 1
    ) s ON t.POLICY_NUMBER = s.POLICY_NUMBER
    WHEN MATCHED THEN UPDATE SET PRODUCT = s.PRODUCT, START_DATE = s.START_DATE, SUM_INSURED = s.SUM_INSURED
    WHEN NOT MATCHED THEN INSERT VALUES (s.POLICY_NUMBER, s.PRODUCT, s.START_DATE, s.SUM_INSURED);

    MERGE INTO CLEAN.CLAIMS t USING (
      SELECT CLAIM_ID, UPPER(TRIM(POLICY_NUMBER)) POLICY_NUMBER, LOSS_DATE, INITCAP(TRIM(LOSS_TYPE)) LOSS_TYPE,
             TRIM(NARRATIVE) NARRATIVE, CLAIMED_AMOUNT, REPORTED_AT
      FROM RAW.CLAIMS_RAW
      WHERE CLAIMED_AMOUNT > 0
      QUALIFY ROW_NUMBER() OVER (PARTITION BY CLAIM_ID ORDER BY INGESTED_AT DESC) = 1
    ) s ON t.CLAIM_ID = s.CLAIM_ID
    WHEN MATCHED THEN UPDATE SET POLICY_NUMBER = s.POLICY_NUMBER, LOSS_DATE = s.LOSS_DATE, LOSS_TYPE = s.LOSS_TYPE,
                                 NARRATIVE = s.NARRATIVE, CLAIMED_AMOUNT = s.CLAIMED_AMOUNT, REPORTED_AT = s.REPORTED_AT
    WHEN NOT MATCHED THEN INSERT VALUES (s.CLAIM_ID, s.POLICY_NUMBER, s.LOSS_DATE, s.LOSS_TYPE, s.NARRATIVE, s.CLAIMED_AMOUNT, s.REPORTED_AT);
  END;

CREATE OR REPLACE TASK CURATED.T_PUBLISH
  WAREHOUSE = CLAIMS_WH
  AFTER CURATED.T_CLEAN
AS
  INSERT INTO CURATED.DAG_RUN_LOG (CLAIMS_TOTAL, UNASSESSED)
  SELECT COUNT(*), COUNT_IF(a.CLAIM_ID IS NULL)
  FROM CLEAN.CLAIMS c
  LEFT JOIN (SELECT DISTINCT CLAIM_ID FROM CURATED.CLAIM_ASSESSMENTS) a USING (CLAIM_ID);

-- Resume children first, root last
ALTER TASK CURATED.T_PUBLISH RESUME;
ALTER TASK CURATED.T_CLEAN RESUME;
ALTER TASK CURATED.T_INGEST RESUME;

-- Run once now instead of waiting for the schedule
EXECUTE TASK CURATED.T_INGEST;

-- Sync source for DAG D (CURATED -> Dataverse): one row per claim with its latest assessment and decision.
CREATE OR REPLACE VIEW CURATED.V_CLAIMS_SYNC AS
SELECT c.CLAIM_ID, c.POLICY_NUMBER, c.LOSS_TYPE, c.LOSS_DATE, c.CLAIMED_AMOUNT, c.NARRATIVE,
       a.ASSESSMENT_ID, a.RECOMMENDATION, a.SUMMARY, a.RATIONALE, a.CLAUSE_IDS AS RECOMMENDED_CLAUSE_IDS, a.CONFIDENCE,
       d.DECISION_ID, d.DECISION, d.OVERRIDE_OF_AGENT, d.REASON AS DECISION_REASON, d.DECIDED_BY, d.DECIDED_AT,
       v.SUPPORTED AS DECISION_SUPPORTED, v.SEVERITY AS VERIFICATION_SEVERITY, v.FINDING AS VERIFICATION_FINDING,
       GREATEST_IGNORE_NULLS(a.CREATED_AT, d.DECIDED_AT, v.VERIFIED_AT, c.REPORTED_AT) AS UPDATED_AT
FROM CLEAN.CLAIMS c
LEFT JOIN CURATED.CLAIM_ASSESSMENTS a ON a.CLAIM_ID = c.CLAIM_ID
  AND a.CREATED_AT = (SELECT MAX(CREATED_AT) FROM CURATED.CLAIM_ASSESSMENTS WHERE CLAIM_ID = c.CLAIM_ID)
LEFT JOIN CURATED.CLAIM_DECISIONS d ON d.CLAIM_ID = c.CLAIM_ID
  AND d.DECIDED_AT = (SELECT MAX(DECIDED_AT) FROM CURATED.CLAIM_DECISIONS WHERE CLAIM_ID = c.CLAIM_ID)
LEFT JOIN CURATED.DECISION_VERIFICATIONS v ON v.DECISION_ID = d.DECISION_ID
  AND v.VERIFIED_AT = (SELECT MAX(VERIFIED_AT) FROM CURATED.DECISION_VERIFICATIONS WHERE DECISION_ID = d.DECISION_ID);
