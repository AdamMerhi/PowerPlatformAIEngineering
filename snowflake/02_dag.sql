-- Task DAG: ingest -> clean -> score -> publish. Run as POC_ROLE.
USE ROLE POC_ROLE;
USE WAREHOUSE CLAIMS_WH;
USE DATABASE CLAIMS_POC;

-- Root: simulate new claims arriving every 5 minutes
CREATE OR REPLACE TASK CURATED.T_INGEST
  WAREHOUSE = CLAIMS_WH
  SCHEDULE = '5 MINUTE'
AS
  INSERT INTO RAW.CLAIMS_RAW (CLAIM_ID, POLICY_NUMBER, LOSS_DATE, LOSS_TYPE, DESCRIPTION, CLAIMED_AMOUNT, REPORTED_AT)
  SELECT 'CLM' || UUID_STRING(),
         'POL' || LPAD(UNIFORM(0, 499, RANDOM())::STRING, 6, '0'),
         DATEADD(day, -UNIFORM(0, 5, RANDOM()), CURRENT_DATE()),
         ARRAY_CONSTRUCT('Collision','Theft','Water damage','Fire','Storm','Medical')[UNIFORM(0,5,RANDOM())]::STRING,
         'Synthetic streaming claim narrative.',
         UNIFORM(200, 150000, RANDOM()),
         CURRENT_TIMESTAMP()
  FROM TABLE(GENERATOR(ROWCOUNT => 5));

CREATE OR REPLACE TASK CURATED.T_CLEAN
  WAREHOUSE = CLAIMS_WH
  AFTER CURATED.T_INGEST
AS
  BEGIN
    MERGE INTO CLEAN.POLICIES t USING (
      SELECT POLICY_NUMBER, PRODUCT, START_DATE, SUM_INSURED FROM RAW.POLICIES_RAW
    ) s ON t.POLICY_NUMBER = s.POLICY_NUMBER
    WHEN MATCHED THEN UPDATE SET PRODUCT = s.PRODUCT, START_DATE = s.START_DATE, SUM_INSURED = s.SUM_INSURED
    WHEN NOT MATCHED THEN INSERT VALUES (s.POLICY_NUMBER, s.PRODUCT, s.START_DATE, s.SUM_INSURED);

    MERGE INTO CLEAN.CLAIMS t USING (
      SELECT CLAIM_ID, UPPER(TRIM(POLICY_NUMBER)) POLICY_NUMBER, LOSS_DATE, INITCAP(TRIM(LOSS_TYPE)) LOSS_TYPE,
             TRIM(DESCRIPTION) DESCRIPTION, CLAIMED_AMOUNT, REPORTED_AT
      FROM RAW.CLAIMS_RAW
      WHERE CLAIMED_AMOUNT > 0
      QUALIFY ROW_NUMBER() OVER (PARTITION BY CLAIM_ID ORDER BY INGESTED_AT DESC) = 1
    ) s ON t.CLAIM_ID = s.CLAIM_ID
    WHEN MATCHED THEN UPDATE SET POLICY_NUMBER = s.POLICY_NUMBER, LOSS_DATE = s.LOSS_DATE, LOSS_TYPE = s.LOSS_TYPE,
                                 DESCRIPTION = s.DESCRIPTION, CLAIMED_AMOUNT = s.CLAIMED_AMOUNT, REPORTED_AT = s.REPORTED_AT
    WHEN NOT MATCHED THEN INSERT VALUES (s.CLAIM_ID, s.POLICY_NUMBER, s.LOSS_DATE, s.LOSS_TYPE, s.DESCRIPTION, s.CLAIMED_AMOUNT, s.REPORTED_AT);
  END;

CREATE OR REPLACE TASK CURATED.T_SCORE
  WAREHOUSE = CLAIMS_WH
  AFTER CURATED.T_CLEAN
AS
  MERGE INTO CURATED.CLAIM_RISK t USING (
    WITH prior AS (
      SELECT POLICY_NUMBER, COUNT(*) CLAIM_COUNT FROM CLEAN.CLAIMS GROUP BY POLICY_NUMBER
    ),
    scored AS (
      SELECT c.CLAIM_ID, c.POLICY_NUMBER,
             LEAST(100,
               LEAST(50, 50 * c.CLAIMED_AMOUNT / NULLIF(p.SUM_INSURED, 0))
               + IFF(DATEDIFF(day, p.START_DATE, c.LOSS_DATE) < 30, 25, 0)
               + LEAST(25, 5 * (pr.CLAIM_COUNT - 1))) AS RISK_SCORE,
             ARRAY_TO_STRING(ARRAY_COMPACT(ARRAY_CONSTRUCT(
               IFF(DATEDIFF(day, p.START_DATE, c.LOSS_DATE) < 30, 'LOSS_SOON_AFTER_INCEPTION', NULL),
               IFF(c.CLAIMED_AMOUNT > 0.5 * p.SUM_INSURED, 'HIGH_AMOUNT_VS_SUM_INSURED', NULL),
               IFF(pr.CLAIM_COUNT >= 4, 'FREQUENT_CLAIMANT', NULL))), ',') AS FRAUD_FLAGS,
             IFF(c.CLAIMED_AMOUNT >= 50000, 'COMPLEX', IFF(c.CLAIMED_AMOUNT >= 10000, 'STANDARD', 'SIMPLE')) AS SEVERITY_HINT
      FROM CLEAN.CLAIMS c
      JOIN CLEAN.POLICIES p USING (POLICY_NUMBER)
      JOIN prior pr USING (POLICY_NUMBER)
    )
    SELECT *, IFF(RISK_SCORE >= 70, 'HIGH', IFF(RISK_SCORE >= 40, 'MEDIUM', 'LOW')) RISK_BAND FROM scored
  ) s ON t.CLAIM_ID = s.CLAIM_ID
  WHEN MATCHED AND (t.RISK_SCORE <> s.RISK_SCORE OR t.FRAUD_FLAGS <> s.FRAUD_FLAGS) THEN UPDATE SET
    RISK_SCORE = s.RISK_SCORE, RISK_BAND = s.RISK_BAND, FRAUD_FLAGS = s.FRAUD_FLAGS,
    SEVERITY_HINT = s.SEVERITY_HINT, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (CLAIM_ID, POLICY_NUMBER, RISK_SCORE, RISK_BAND, FRAUD_FLAGS, SEVERITY_HINT)
    VALUES (s.CLAIM_ID, s.POLICY_NUMBER, s.RISK_SCORE, s.RISK_BAND, s.FRAUD_FLAGS, s.SEVERITY_HINT);

CREATE OR REPLACE TASK CURATED.T_PUBLISH
  WAREHOUSE = CLAIMS_WH
  AFTER CURATED.T_SCORE
AS
  INSERT INTO CURATED.DAG_RUN_LOG (CLAIMS_TOTAL, HIGH_RISK)
  SELECT COUNT(*), COUNT_IF(RISK_BAND = 'HIGH') FROM CURATED.CLAIM_RISK;

-- Resume children first, root last
ALTER TASK CURATED.T_PUBLISH RESUME;
ALTER TASK CURATED.T_SCORE RESUME;
ALTER TASK CURATED.T_CLEAN RESUME;
ALTER TASK CURATED.T_INGEST RESUME;

-- Run once now instead of waiting for the schedule
EXECUTE TASK CURATED.T_INGEST;

-- Sync source for the Dataverse function (rows changed since a watermark)
CREATE OR REPLACE VIEW CURATED.V_CLAIM_RISK_SYNC AS
SELECT r.CLAIM_ID, r.POLICY_NUMBER, r.RISK_SCORE, r.RISK_BAND, r.FRAUD_FLAGS, r.SEVERITY_HINT,
       c.LOSS_TYPE, c.CLAIMED_AMOUNT, c.LOSS_DATE, r.UPDATED_AT
FROM CURATED.CLAIM_RISK r JOIN CLEAN.CLAIMS c USING (CLAIM_ID);
