-- Run ONCE by you as ACCOUNTADMIN (trial/dev account only).
-- Creates an isolated, low-cost sandbox and a least-privilege service user.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS POC_ROLE;

CREATE WAREHOUSE IF NOT EXISTS CLAIMS_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Cost guard: suspend the warehouse after 5 credits.
CREATE RESOURCE MONITOR IF NOT EXISTS CLAIMS_POC_RM
  WITH CREDIT_QUOTA = 5
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE CLAIMS_WH SET RESOURCE_MONITOR = CLAIMS_POC_RM;

CREATE DATABASE IF NOT EXISTS CLAIMS_POC;
CREATE SCHEMA IF NOT EXISTS CLAIMS_POC.RAW;
CREATE SCHEMA IF NOT EXISTS CLAIMS_POC.CLEAN;
CREATE SCHEMA IF NOT EXISTS CLAIMS_POC.CURATED;

GRANT USAGE, OPERATE ON WAREHOUSE CLAIMS_WH TO ROLE POC_ROLE;
GRANT ALL ON DATABASE CLAIMS_POC TO ROLE POC_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE CLAIMS_POC TO ROLE POC_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE POC_ROLE;

-- Service user with key-pair auth. Generate a key locally, paste the PUBLIC key (no header/footer):
--   openssl genrsa 2048 | openssl pkcs8 -topk8 -inform PEM -out poc_svc.p8 -nocrypt
--   openssl rsa -in poc_svc.p8 -pubout -out poc_svc.pub
CREATE USER IF NOT EXISTS POC_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = POC_ROLE
  DEFAULT_WAREHOUSE = CLAIMS_WH
  RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY_HERE>';
GRANT ROLE POC_ROLE TO USER POC_SVC;
